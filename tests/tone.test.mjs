import assert from 'node:assert/strict';
import { analyze, correctTone } from '../src/tone.mjs';
import { isVKPage, permittedImage } from '../extension/image-policy.js';
const raster = value => new Uint8ClampedArray(Array.from({length:1000},() => [value,value,value,255]).flat());
const bright = raster(215), dark = raster(55), normal = raster(125);
const bs = correctTone(bright), ds = correctTone(dark);
correctTone(normal);
assert.ok(bs.gamma > 1 && bright[0] < 215 && bright[0] > 160);
assert.ok(ds.gamma < 1 && dark[0] > 55 && dark[0] < 100);
assert.ok(Math.abs(normal[0]-125) < 15);
const extremes = new Uint8ClampedArray([0,0,0,255,255,255,255,255,80,50,40,0]);
correctTone(extremes);
assert.deepEqual([...extremes], [0,0,0,255,255,255,255,255,80,50,40,0]);
assert.ok(isVKPage('https://vk.ru/photo-1_2'));
for (const bad of ['https://vk.ru.evil.test/','https://evil-vk.ru/','http://vk.ru/']) assert.equal(isVKPage(bad),false);
assert.ok(permittedImage('https://sun9-18.userapi.com/impg/image.jpg?secret=signed'));
for (const bad of ['http://sun9.userapi.com/x','https://userapi.com.evil.test/x','https://127.0.0.1/x','file:///C:/test','https://name:pass@userapi.com/x','https://userapi.com:8443/x']) assert.equal(permittedImage(bad),false);
assert.ok(analyze(raster(128)).pixels===1000);
console.log('PASS: tone curve bright/dark/normal, clipped endpoints, alpha and network allowlist.');
